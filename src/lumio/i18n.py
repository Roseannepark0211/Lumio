def _get_lang() -> str:
    global _LANG
    if _LANG is None:
        _LANG = load_config().get("lang", "zh")
    return _LANG


def t(key: str, *args, **kwargs) -> str:
    """翻译 key 对应的文本。

    支持两种占位符语法（保持向后兼容）：
    - 位置参数：`t("notif_xxx_msg", "value1", "value2")` → 模板 `{0}` `{1}`
    - 关键字参数：`t("notif_xxx_msg", name="value")` → 模板 `{name}`

    重构背景：notification_manager 早期调用使用位置参数，旧版 t() 仅支持
    kwargs，导致 `TypeError: t() takes 1 positional argument but 2 were given`。
    """
    lang = _get_lang()
    text = _TRANSLATIONS.get(lang, _TRANSLATIONS["zh"]).get(key, key)
    if args or kwargs:
        text = text.format(*args, **kwargs)
    return text


def get_lang() -> str:
    return _get_lang()


def set_lang(lang: str) -> None:
    global _LANG
    _LANG = lang
    cfg = load_config()
    cfg["lang"] = lang
    save_config(cfg)
