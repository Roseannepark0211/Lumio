def _get_lang() -> str:
    global _LANG
    if _LANG is None:
        _LANG = load_config().get("lang", "zh")
    return _LANG


def t(key: str, **kwargs) -> str:
    lang = _get_lang()
    text = _TRANSLATIONS.get(lang, _TRANSLATIONS["zh"]).get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text


def get_lang() -> str:
    return _get_lang()


def set_lang(lang: str) -> None:
    global _LANG
    _LANG = lang
    cfg = load_config()
    cfg["lang"] = lang
    save_config(cfg)
