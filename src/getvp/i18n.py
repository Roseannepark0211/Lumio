def t(key: str, **kwargs) -> str:
    text = _TRANSLATIONS.get(_LANG, _TRANSLATIONS["zh"]).get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text


def get_lang() -> str:
    return _LANG


def set_lang(lang: str) -> None:
    global _LANG
    _LANG = lang
    cfg = load_config()
    cfg["lang"] = lang
    save_config(cfg)
